import json
import logging
import re
from datetime import date, datetime, timezone
from pathlib import Path

from flask import Flask, jsonify, request

app = Flask(__name__)
app.logger.setLevel(logging.INFO)

# Keep courses.json beside app.py.
DATA_FILE = Path(__file__).resolve().parent / "courses.json"

VALID_STATUSES = {"Not Started", "In Progress", "Completed"}
REQUIRED_FIELDS = {"name", "description", "target_date", "status"}


class StorageError(Exception):
    """Raised when the course file can't be read or written."""


def ensure_data_file():
    """Create courses.json with an empty list if it doesn't exist."""
    try:
        # Create the file exclusively so an existing file isn't overwritten.
        with DATA_FILE.open("x", encoding="utf-8") as file:
            json.dump([], file)
    except FileExistsError:
        # The file already exists, so leave its contents unchanged.
        pass
    except OSError as error:
        raise StorageError(f"Could not create the course file: {error}") from error


def load_courses():
    """Read and return all courses from courses.json."""
    ensure_data_file()

    try:
        with DATA_FILE.open("r", encoding="utf-8") as file:
            courses = json.load(file)
    except json.JSONDecodeError as error:
        raise StorageError("courses.json contains invalid JSON.") from error
    except OSError as error:
        raise StorageError(f"Could not read courses.json: {error}") from error

    # The file should contain a JSON list of courses.
    if not isinstance(courses, list):
        raise StorageError("courses.json must contain a JSON list.")

    return courses


def save_courses(courses):
    """Write all courses to the JSON file."""
    temp_file = DATA_FILE.with_name(DATA_FILE.name + ".tmp")

    try:
        # Write to a temporary file first, then replace the original file.
        with temp_file.open("w", encoding="utf-8") as file:
            json.dump(courses, file, indent=2)
            file.write("\n")

        temp_file.replace(DATA_FILE)
    except OSError as error:
        # Try to remove a leftover temporary file if writing failed.
        try:
            temp_file.unlink(missing_ok=True)
        except OSError:
            pass

        raise StorageError(f"Could not write courses.json: {error}") from error


def validate_course_fields(data):
    """Check required fields and their formats. Return an error or None."""
    if not isinstance(data, dict):
        return "The request body must be a JSON object."

    missing_fields = REQUIRED_FIELDS - data.keys()
    if missing_fields:
        return f"Missing required fields: {', '.join(sorted(missing_fields))}."

    # IDs and timestamps are generated by the server.
    unexpected_fields = data.keys() - REQUIRED_FIELDS
    if unexpected_fields:
        return f"These fields cannot be provided: {', '.join(sorted(unexpected_fields))}."

    if not isinstance(data["name"], str) or not data["name"].strip():
        return "name must be a non-empty string."

    if not isinstance(data["description"], str) or not data["description"].strip():
        return "description must be a non-empty string."

    if data["status"] not in VALID_STATUSES:
        return 'status must be "Not Started", "In Progress", or "Completed".'

    # Require exactly YYYY-MM-DD, not just any date format Python accepts.
    target_date = data["target_date"]
    if not isinstance(target_date, str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", target_date):
        return "target_date must use YYYY-MM-DD format."

    try:
        date.fromisoformat(target_date)
    except ValueError:
        return "target_date must be a valid calendar date in YYYY-MM-DD format."

    return None


def get_json_body():
    """Get a JSON request body, returning a helpful error if it is missing."""
    data = request.get_json(silent=True)
    if data is None:
        return None, "Request body must contain valid JSON."
    if not isinstance(data, dict):
        return None, "The request body must be a JSON object."
    return data, None


@app.post("/api/courses")
def create_course():
    """Add a course and assign its ID and creation timestamp."""
    data, body_error = get_json_body()
    if body_error:
        return jsonify(error=body_error), 400

    validation_error = validate_course_fields(data)
    if validation_error:
        return jsonify(error=validation_error), 400

    try:
        courses = load_courses()

        # Assign the next ID. An empty course list starts at ID 1.
        try:
            next_id = max((course["id"] for course in courses), default=0) + 1
        except (KeyError, TypeError) as error:
            raise StorageError("A course in courses.json has an invalid ID.") from error

        course = {
            "id": next_id,
            "name": data["name"].strip(),
            "description": data["description"].strip(),
            "target_date": data["target_date"],
            "status": data["status"],
            "created_at": datetime.now(timezone.utc).isoformat(),
        }

        courses.append(course)
        save_courses(courses)

        return jsonify(course), 201

    except StorageError as error:
        app.logger.exception("Course storage error")
        return jsonify(error=str(error)), 500


@app.get("/api/courses")
def get_all_courses():
    """Return all courses."""
    try:
        return jsonify(load_courses()), 200
    except StorageError as error:
        app.logger.exception("Course storage error")
        return jsonify(error=str(error)), 500


@app.get("/api/courses/<int:course_id>")
def get_course(course_id):
    """Return one course by ID."""
    try:
        courses = load_courses()
        course = next((item for item in courses if item.get("id") == course_id), None)

        if course is None:
            return jsonify(error="Course not found."), 404

        return jsonify(course), 200

    except StorageError as error:
        app.logger.exception("Course storage error")
        return jsonify(error=str(error)), 500


@app.put("/api/courses/<int:course_id>")
def update_course(course_id):
    """Replace a course's editable fields while preserving its ID and timestamp."""
    data, body_error = get_json_body()
    if body_error:
        return jsonify(error=body_error), 400

    validation_error = validate_course_fields(data)
    if validation_error:
        return jsonify(error=validation_error), 400

    try:
        courses = load_courses()
        course = next((item for item in courses if item.get("id") == course_id), None)

        if course is None:
            return jsonify(error="Course not found."), 404

        # Keep id and created_at unchanged; update the required course fields.
        course.update({
            "name": data["name"].strip(),
            "description": data["description"].strip(),
            "target_date": data["target_date"],
            "status": data["status"],
        })

        save_courses(courses)
        return jsonify(course), 200

    except StorageError as error:
        app.logger.exception("Course storage error")
        return jsonify(error=str(error)), 500


@app.delete("/api/courses/<int:course_id>")
def delete_course(course_id):
    """Delete a course by ID."""
    try:
        courses = load_courses()
        remaining_courses = [
            course for course in courses
            if course.get("id") != course_id
        ]

        if len(remaining_courses) == len(courses):
            return jsonify(error="Course not found."), 404

        save_courses(remaining_courses)
        return "", 204

    except StorageError as error:
        app.logger.exception("Course storage error")
        return jsonify(error=str(error)), 500


if __name__ == "__main__":
    # Try creating the JSON file when the app starts.
    # Storage operations also check for it, in case startup creation fails.
    try:
        ensure_data_file()
    except StorageError:
        app.logger.exception("Could not initialize courses.json")

    app.run(debug=True)